# Qualquer calculo que envolva apenas valores integers
# o valor também será integer, independentemente do cálculo
puts 10/2
# Já se houver pelo menos 1 valor float, o resultado será float.
puts 10/2.5
puts 1 + 1
puts 1 + 1.0
# Potenciação
puts 10**2
# Métodos para números
puts 2.6.round()
puts 2.6.ceil()
puts 2.6.floor()
# Classe que disponibiliza métodos matemáticos
puts Math.log(1)